import { createServer } from 'vite';
import { writeFile } from 'node:fs/promises';
const vite = await createServer({server:{middlewareMode:true},appType:'custom'});
try {
  const { atlasLocalities, atlasLocalityPath } = await vite.ssrLoadModule('/src/data/atlas/index.ts');
  const { localPlaceReadings, placeLabel } = await vite.ssrLoadModule('/src/data/language-names.ts');
  const covered = atlasLocalities.filter(p=>localPlaceReadings[p.id]);
  const escape = text => text.replace(/\|/g,'\\|');
  const lines = ['# Place-name coverage', '', 'Generated by `npm run audit:names` from the shared name registry. Counts refer to sourced name spellings, not IPA or complete dialect documentation.', '',
    `${atlasLocalities.length} localities · ${covered.length} with a sourced local reading · ${atlasLocalities.length-covered.length} still awaiting local-name evidence.`, '',
    'Common names remain when a local reading is unavailable. Mandarin pinyin and neighbouring-dialect readings are never invented as substitutes. The independently documented Kulangsu landmark is not counted as a dialect locality.', '',
    '| Common name | Local reading | Convention / status | Locality | Source |',
    '| --- | --- | --- | --- | --- |'];
  for(const point of atlasLocalities) {
    const reading=localPlaceReadings[point.id];
    lines.push(`| ${escape(placeLabel(point))} | ${escape(reading?.localName??'—')} | ${escape(reading?.convention??'Local reading not yet sourced')} | ${point.groupId} · ${point.nativeName} | ${reading ? `[Name source](${reading.source.url})` : `[Locality record](https://hanlingo.pairup.world${atlasLocalityPath(point)})`} |`);
  }
  await writeFile('docs/PLACE-NAME-COVERAGE.md',lines.join('\n')+'\n');
  console.log(`${covered.length}/${atlasLocalities.length} locality name readings; ${atlasLocalities.length-covered.length} explicit gaps.`);
} finally { await vite.close(); }
